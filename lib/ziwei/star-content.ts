/** 生成完整 STAR_DB：14 主星 × 13 主题 */
export function buildStarDb(): Record<string, Record<string, string>> {
  const db: Record<string, Record<string, string>> = {};
  for (const s of P) {
    const fields: Record<string, string> = {};
    // TopicKey → StarContent 字段名
    const map: [TopicKey, string][] = [
      ['overview', 'mingGong'], ['personality', 'personality'], ['love', 'fuQi'],
      ['career', 'guanLu'], ['wealth', 'caiBo'], ['health', 'jiE'],
      ['family', 'xiongDi'], ['children', 'ziNv'], ['move', 'qianYi'],
      ['friends', 'jiaoYou'], ['home', 'tianZhai'], ['spirit', 'fuDe'], ['parents', 'fuMu'],
    ];
    for (const [topic, field] of map) fields[field] = buildContent(s, topic);
    db[s.name] = fields;
  }
  return db;
}
